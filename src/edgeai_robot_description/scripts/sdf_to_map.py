#!/usr/bin/env python3
"""Rasterize a Gazebo world's static box geometry into a Nav2 occupancy map (PGM + YAML).

The map frame equals the world frame (no rotation, no offset), so poses in the world file,
scenarios/*.yaml and the target lists can all be used directly in the map frame.

What gets drawn: every <box> collision of every static model in the world, including models
pulled in with <include><uri>model://NAME</uri>, which are resolved from --models. Planes are ignored.
Poses are composed in 2D (x, y, yaw). Each box is grown by half a cell so that thin walls
always cover whole cells. Cells outside the bounding box of all geometry are marked unknown.

Usage (defaults rebuild the midterm map):
    python3 sdf_to_map.py [--world worlds/midterm_arena.sdf] [--out maps/midterm_arena]
                          [--models models] [--resolution 0.05] [--margin 0.1]
"""
import argparse
import math
import os
import xml.etree.ElementTree as ET

import numpy as np

PKG = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
FREE, OCCUPIED, UNKNOWN = 254, 0, 205


def parse_pose(elem):
    """(x, y, yaw) from an element's <pose> child (roll and pitch are ignored)."""
    pose = elem.find('pose') if elem is not None else None
    if pose is None or not pose.text:
        return (0.0, 0.0, 0.0)
    v = [float(t) for t in pose.text.split()]
    return (v[0], v[1], v[5] if len(v) >= 6 else 0.0)


def compose(a, b):
    """Pose b expressed in frame a -> pose in a's parent frame."""
    ax, ay, ath = a
    bx, by, bth = b
    c, s = math.cos(ath), math.sin(ath)
    return (ax + c * bx - s * by, ay + s * bx + c * by, ath + bth)


def model_boxes(model, frame, models_dir):
    """All box collisions of a <model> element as (x, y, yaw, sx, sy) in the world frame."""
    boxes = []
    frame = compose(frame, parse_pose(model))
    for link in model.findall('link'):
        link_frame = compose(frame, parse_pose(link))
        for col in link.findall('collision'):
            size = col.find('geometry/box/size')
            if size is None:
                continue
            sx, sy, _ = (float(t) for t in size.text.split())
            x, y, yaw = compose(link_frame, parse_pose(col))
            boxes.append((x, y, yaw, sx, sy))
    for sub in model.findall('model'):
        boxes += model_boxes(sub, frame, models_dir)
    return boxes


def world_boxes(world_path, models_dir):
    world = ET.parse(world_path).getroot().find('world')
    boxes = []
    for model in world.findall('model'):
        boxes += model_boxes(model, (0.0, 0.0, 0.0), models_dir)
    for inc in world.findall('include'):
        uri = inc.find('uri').text.strip()
        if not uri.startswith('model://'):
            raise ValueError(f'unsupported include uri {uri!r}')
        model_sdf = os.path.join(models_dir, uri[len('model://'):], 'model.sdf')
        model = ET.parse(model_sdf).getroot().find('model')
        # The include's <pose> replaces the model's own top-level pose
        include_pose = parse_pose(inc)
        own = parse_pose(model)
        frame = compose(include_pose, (-own[0], -own[1], -own[2])) if inc.find('pose') is not None else (0, 0, 0)
        boxes += model_boxes(model, frame, models_dir)
    return boxes


def rasterize(boxes, resolution, margin):
    corners = []
    for x, y, yaw, sx, sy in boxes:
        c, s = math.cos(yaw), math.sin(yaw)
        for dx, dy in ((sx / 2, sy / 2), (-sx / 2, sy / 2), (sx / 2, -sy / 2), (-sx / 2, -sy / 2)):
            corners.append((x + c * dx - s * dy, y + s * dx + c * dy))
    xs, ys = zip(*corners)
    lo_x, lo_y, hi_x, hi_y = min(xs), min(ys), max(xs), max(ys)
    x0 = math.floor((lo_x - margin) / resolution) * resolution
    y0 = math.floor((lo_y - margin) / resolution) * resolution
    w = int(math.ceil((hi_x + margin - x0) / resolution))
    h = int(math.ceil((hi_y + margin - y0) / resolution))

    # Cell centres, row 0 = lowest y (OccupancyGrid convention)
    cx = x0 + (np.arange(w) + 0.5) * resolution
    cy = y0 + (np.arange(h) + 0.5) * resolution
    gx, gy = np.meshgrid(cx, cy)
    img = np.full((h, w), FREE, dtype=np.uint8)
    img[(gx < lo_x) | (gx > hi_x) | (gy < lo_y) | (gy > hi_y)] = UNKNOWN
    grow = resolution / 2
    for x, y, yaw, sx, sy in boxes:
        c, s = math.cos(yaw), math.sin(yaw)
        lx = c * (gx - x) + s * (gy - y)
        ly = -s * (gx - x) + c * (gy - y)
        img[(np.abs(lx) <= sx / 2 + grow) & (np.abs(ly) <= sy / 2 + grow)] = OCCUPIED
    return np.flipud(img), (round(x0, 6), round(y0, 6))  # image row 0 = top


def write_map(prefix, img, origin, resolution):
    h, w = img.shape
    with open(prefix + '.pgm', 'wb') as f:
        f.write(f'P5\n# generated by sdf_to_map.py\n{w} {h}\n255\n'.encode())
        f.write(img.tobytes())
    with open(prefix + '.yaml', 'w') as f:
        f.write(f'# Generated by scripts/sdf_to_map.py from the Gazebo world; map frame = world frame.\n'
                f'image: {os.path.basename(prefix)}.pgm\n'
                f'mode: trinary\n'
                f'resolution: {resolution}\n'
                f'origin: [{origin[0]}, {origin[1]}, 0.0]\n'
                f'negate: 0\n'
                f'occupied_thresh: 0.65\n'
                f'free_thresh: 0.25\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--world', default=os.path.join(PKG, 'worlds', 'midterm_arena.sdf'))
    ap.add_argument('--out', default=os.path.join(PKG, 'maps', 'midterm_arena'), help='output path without extension')
    ap.add_argument('--models', default=os.path.join(PKG, 'models'))
    ap.add_argument('--resolution', type=float, default=0.05)
    ap.add_argument('--margin', type=float, default=0.1, help='unknown border around the geometry [m]')
    args = ap.parse_args()

    boxes = world_boxes(args.world, args.models)
    img, origin = rasterize(boxes, args.resolution, args.margin)
    write_map(args.out, img, origin, args.resolution)
    h, w = img.shape
    print(f'{len(boxes)} boxes -> {w} x {h} cells at {args.resolution} m, origin {origin}: '
          f'{args.out}.pgm / .yaml')


if __name__ == '__main__':
    main()
