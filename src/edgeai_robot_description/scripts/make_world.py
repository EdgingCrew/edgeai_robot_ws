#!/usr/bin/env python3
"""Generate a scenario's Gazebo world and Nav2 map from its layout (scenarios/<name>.yaml).

Writes worlds/<world> (boundary walls, inner walls, obstacle boxes and one ArUco stand per target)
and rasterizes it into maps/<map>.pgm/.yaml with sdf_to_map.py, so world frame = map frame.
Stands come from the scenario's targets file (edgeai_rescue/config/<targets>): stand
model://aruco_stand_<marker> at (x, y), rotated to face `yaw`. Generate missing stand models first
with make_aruco_stands.py.

Usage: python3 make_world.py [scenario ...]     (default: every scenario in scenarios/)
"""
import argparse
import glob
import math
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sdf_to_map  # noqa: E402

PKG = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
RESCUE_CONFIG = os.path.normpath(os.path.join(PKG, '..', 'edgeai_rescue', 'config'))

WALL_THICKNESS, WALL_HEIGHT, OBSTACLE_HEIGHT = 0.1, 0.5, 0.4
WALL_COLOUR, OBSTACLE_COLOUR = '0.35 0.35 0.35 1', '0.55 0.45 0.35 1'

HEADER = """<?xml version="1.0" ?>
<!--
  {title}
  Generated by scripts/make_world.py from scenarios/{scenario}.yaml - edit that file, not this one.
  World frame = map frame: maps/{map_name} is rasterized from this file.
-->

<sdf version="1.9">

  <world name="{world_name}">

    <!-- Physics -->
    <physics name="physics" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <!-- Gazebo core systems -->
    <plugin
      filename="gz-sim-physics-system"
      name="gz::sim::systems::Physics"/>

    <plugin
      filename="gz-sim-user-commands-system"
      name="gz::sim::systems::UserCommands"/>

    <plugin
      filename="gz-sim-scene-broadcaster-system"
      name="gz::sim::systems::SceneBroadcaster"/>

    <!-- Required for GPU LiDAR / camera sensors -->
    <plugin
      filename="gz-sim-sensors-system"
      name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <!-- Ground -->
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material>
            <ambient>0.8 0.8 0.8 1</ambient>
            <diffuse>0.8 0.8 0.8 1</diffuse>
            <specular>0.0 0.0 0.0 1</specular>
          </material>
        </visual>
      </link>
    </model>

"""

FOOTER = """    <!-- Lighting -->
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.7 0.7 0.7 1</diffuse>
      <specular>0.0 0.0 0.0 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <scene>
      <ambient>0.5 0.5 0.5 1</ambient>
      <background>0.15 0.15 0.15 1</background>
      <shadows>true</shadows>
    </scene>

  </world>

</sdf>
"""


def fmt(v):
    return f'{round(v, 6):g}'


def box_model(name, comment, x, y, yaw, sx, sy, height, colour):
    size = f'{fmt(sx)} {fmt(sy)} {fmt(height)}'
    return f"""    <!-- {name}: {comment} -->
    <model name="{name}">
      <static>true</static>
      <pose>{fmt(x)} {fmt(y)} {fmt(height / 2)} 0 0 {fmt(yaw)}</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{size}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{size}</size></box></geometry>
          <material><ambient>{colour}</ambient><diffuse>{colour}</diffuse></material>
        </visual>
      </link>
    </model>

"""


def wall_box(x0, y0, x1, y1):
    """(x, y, yaw, sx, sy) of a wall spanning exactly (x0, y0) -> (x1, y1) along its centre line."""
    length = math.hypot(x1 - x0, y1 - y0)
    if length == 0:
        raise ValueError('zero-length wall')
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    # Axis-aligned walls are written without rotation so the map raster has no rounding noise
    if y0 == y1:
        return cx, cy, 0.0, length, WALL_THICKNESS
    if x0 == x1:
        return cx, cy, 0.0, WALL_THICKNESS, length
    return cx, cy, math.atan2(y1 - y0, x1 - x0), length, WALL_THICKNESS


def scenario_path(name):
    return name if name.endswith('.yaml') else os.path.join(PKG, 'scenarios', f'{name}.yaml')


def world_sdf(scenario_file):
    """(scenario dict, SDF text, number of targets) for a scenario file."""
    with open(scenario_file) as f:
        sc = yaml.safe_load(f)
    name = os.path.splitext(os.path.basename(scenario_file))[0]
    layout = sc['layout']
    with open(os.path.join(RESCUE_CONFIG, sc['targets'])) as f:
        targets = yaml.safe_load(f)['targets']

    title = (layout.get('title') or f'Scenario {name}').strip()
    out = [HEADER.format(title=title, scenario=name, map_name=os.path.splitext(sc['map'])[0] + '.*',
                         world_name=os.path.splitext(sc['world'])[0])]

    t, (w, h) = WALL_THICKNESS, layout['size']
    out.append('    <!-- Boundary walls (inner faces on the edges of the [0, w] x [0, h] area) -->\n\n')
    for wall, x, y, sx, sy in (('south_wall', w / 2, -t / 2, w + 2 * t, t),
                               ('north_wall', w / 2, h + t / 2, w + 2 * t, t),
                               ('west_wall', -t / 2, h / 2, t, h + 2 * t),
                               ('east_wall', w + t / 2, h / 2, t, h + 2 * t)):
        out.append(box_model(wall, 'boundary', x, y, 0.0, sx, sy, WALL_HEIGHT, WALL_COLOUR))

    if layout.get('walls'):
        out.append('    <!-- Inner walls -->\n\n')
    for i, wall in enumerate(layout.get('walls') or []):
        (x0, y0), (x1, y1) = wall['from'], wall['to']
        x, y, yaw, sx, sy = wall_box(x0, y0, x1, y1)
        out.append(box_model(wall.get('name', f'wall_{i}'), f'({fmt(x0)}, {fmt(y0)}) -> ({fmt(x1)}, {fmt(y1)})',
                             x, y, yaw, sx, sy, WALL_HEIGHT, WALL_COLOUR))

    if layout.get('obstacles'):
        out.append('    <!-- Obstacle boxes -->\n\n')
    for i, ob in enumerate(layout.get('obstacles') or []):
        out.append(box_model(ob.get('name', f'obstacle_{i}'),
                             f"centre ({fmt(ob['x'])}, {fmt(ob['y'])}), {fmt(ob['sx'])} x {fmt(ob['sy'])}",
                             ob['x'], ob['y'], ob.get('yaw', 0.0), ob['sx'], ob['sy'], OBSTACLE_HEIGHT,
                             OBSTACLE_COLOUR))

    out.append('    <!-- Targets: ArUco stands, pose = target reference point, yaw = direction the marker faces -->\n\n')
    for tgt in targets:
        if 'marker' not in tgt:
            raise ValueError(f"{sc['targets']}: target {tgt['id']} has no `marker` id for its stand")
        model = os.path.join(PKG, 'models', f"aruco_stand_{tgt['marker']}")
        if not os.path.isdir(model):
            raise FileNotFoundError(f'{model} missing: run make_aruco_stands.py --ids {tgt["marker"]}')
        out.append(f"""    <include>
      <name>target_{tgt['id']}</name>
      <uri>model://aruco_stand_{tgt['marker']}</uri>
      <pose>{fmt(tgt['x'])} {fmt(tgt['y'])} 0 0 0 {fmt(tgt.get('yaw', 0.0))}</pose>
    </include>

""")
    out.append(FOOTER)
    return sc, ''.join(out), len(targets)


def world_map(world_file):
    """Occupancy image and origin of a world file (0.05 m cells, 0.1 m unknown border)."""
    boxes = sdf_to_map.world_boxes(world_file, os.path.join(PKG, 'models'))
    return sdf_to_map.rasterize(boxes, 0.05, 0.1)


def build_world(scenario_file):
    sc, text, n_targets = world_sdf(scenario_file)
    name = os.path.splitext(os.path.basename(scenario_file))[0]
    world_file = os.path.join(PKG, 'worlds', sc['world'])
    with open(world_file, 'w') as f:
        f.write(text)

    map_prefix = os.path.join(PKG, 'maps', os.path.splitext(sc['map'])[0])
    img, origin = world_map(world_file)
    sdf_to_map.write_map(map_prefix, img, origin, 0.05)
    print(f'{name}: {os.path.relpath(world_file, PKG)}, {os.path.relpath(map_prefix, PKG)}.pgm/.yaml '
          f'({img.shape[1]} x {img.shape[0]} cells, {n_targets} targets)')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('scenarios', nargs='*', help='scenario names or paths (default: all)')
    args = ap.parse_args()
    files = [scenario_path(s) for s in args.scenarios] or sorted(glob.glob(os.path.join(PKG, 'scenarios', '*.yaml')))
    for f in files:
        build_world(f)


if __name__ == '__main__':
    main()
